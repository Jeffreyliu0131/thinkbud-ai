import type { GradeAdapter } from '../grade-adapters'

/**
 * 数学学科模块 — 策略工具箱 + 概念熟悉度
 */
export function buildMathPrompt(adapter: GradeAdapter): string {
  const toolbox = adapter.grade === 'lower'
    ? `数学策略工具箱：
- 加法：凑十法 → 拆分法 → 数数法（仅完全卡住时）
- 减法：退位借十 → 想加算减 → 倒数法
- 乘法：拆分法 → 口诀表引导
- 比较/排序：数轴、画圈`
    : `数学策略工具箱：
- 计算题：拆分凑整、分步估算、逆运算验证
- 应用题：画线段图、列表整理已知条件、找等量关系
- 几何题：标注已知、找辅助线、面积拆分
- 分数/比例：画饼图、找单位一、通分比较
- 方程题：天平模型（"两边要保持平衡"）、逆运算倒推`

  const conceptFamiliarity = adapter.grade === 'lower'
    ? `概念熟悉度参考（1-3年级）：
- 20以内加减法：已学 → 提示回忆，少脚手架
- 两位数加减法：新概念 → 更多脚手架，更小步骤
- 乘法口诀：新概念 → 更多脚手架，更小步骤
- 多位数乘除法：新概念 → 更多脚手架，更小步骤
- 不在列表中的题型 → 默认按已学处理`
    : `概念熟悉度参考（4-6年级）：
- 基础四则运算：已学 → 提示回忆，少脚手架
- 分数基础：新概念 → 更多脚手架，更小步骤
- 小数运算：新概念 → 更多脚手架，更小步骤
- 简易方程：新概念 → 更多脚手架，更小步骤
- 比例/百分数：新概念 → 更多脚手架，更小步骤
- 不在列表中的题型 → 默认按已学处理`

  return `
## 当前学科：数学

${toolbox}

${conceptFamiliarity}`
}
