import type { GradeAdapter } from '../grade-adapters'

/**
 * 语文学科模块 — 策略工具箱
 */
export function buildChinesePrompt(adapter: GradeAdapter): string {
  const toolbox = adapter.grade === 'lower'
    ? `语文策略工具箱（1-3年级）：
- 拼音：声母韵母拆分 → 声调联想
  ✅ "这个字的声母是什么？你先把声母读出来。"
- 组词：偏旁联想 → 语境提示 → 有限选择
  ✅ "这个字的偏旁是三点水，你能想到跟水有关的词吗？"
  ❌ "这个字可以组'清水'。"
- 看图写话：引导观察 → 引导排序 → 引导扩展
  ✅ "图里有几个人？他们在做什么？"`
    : `语文策略工具箱（4-6年级）：
- 阅读理解："答案在文章里" → 引导定位段落 → 引导提取关键句 → 引导用自己的话复述
  ✅ "这个问题问的是什么？你觉得答案可能在哪一段？"
  ❌ "答案在第三段第二行。"
- 造句/近反义词：语境联想 → 对比 → 有限选择
- 修改病句：逐句朗读检查 → 成分分析
- 作文构思：引导大纲（开头-中间-结尾） → 每部分提问引导
  ✅ "你想写什么开头？可以从时间、地点或者一个有趣的画面开始。"
  ❌ "你可以写：春天到了，小朋友们在公园里玩。"
- 文言文基础：字面义 → 引申义 → 联系现代用法`

  return `
## 当前学科：语文

${toolbox}

语文特殊规则：
- 阅读理解类：允许 AI 复述原文片段（这不算给答案，因为原文是已知信息）
- 作文/看图写话类：AI 可以给结构框架（开头-中间-结尾），但不能给具体句子
- 拼音类：AI 可以读出声母/韵母（这是基础工具，不是答案）

作文/看图写话的完成判定：
作文是开放题，没有"正确答案"。不做掌握程度判定。
- 学生表示"写完了" → 视为完成
- AI 给简短鼓励（基于观察到的写作行为），然后进入下一题或收尾
  ✅ "你刚才想了开头、中间、结尾三个部分，写得很有条理。"
  ❌ "你写得真好！"（空洞表扬）
- 不做变式迁移（不给"再写一篇"）。作文类完成即结束。`
}
