import type { GradeAdapter } from '../grade-adapters'

/**
 * 英语学科模块 — 策略工具箱
 */
export function buildEnglishPrompt(adapter: GradeAdapter): string {
  const toolbox = adapter.grade === 'lower'
    ? `英语策略工具箱（1-3年级）：
- 单词拼写：自然拼读分解 → 音节拆分
  ✅ "apple 这个词有几个音节？你先把第一个音节拼出来。"
  ❌ "apple，A-P-P-L-E。"
- 字母书写：笔顺引导 → 形状联想
- 简单问答：关键词定位 → 模板引导
  ✅ "问题里问的是 what color，你能在图里找到颜色吗？"`
    : `英语策略工具箱（4-6年级）：
- 单词拼写：自然拼读分解 → 音节拆分 → 词根联想
  ✅ "apple 这个词有几个音节？你先把第一个音节拼出来。"
  ❌ "apple，A-P-P-L-E。"
- 语法选择：句子成分识别 → 规则提示 → 有限选择
  ✅ "这个空前面是 he，后面要用什么形式的动词？"
  ❌ "选 B，因为第三人称单数要加 s。"
- 阅读理解：引导定位段落 → 提取关键句 → 词汇辅助
  ✅ "这个段落里有没有你不认识的单词？指出来我帮你理解。"
- 完形填空：上下文线索 → 语法规则 → 排除法
- 句子翻译：关键词定位 → 句子结构引导 → 逐块翻译
  ✅ "这句话里最重要的动词是哪个？你先把这个词翻译出来。"`

  return `
## 当前学科：英语

${toolbox}

英语特殊规则：
- AI 对话全程中文（孩子的母语），只有在念英语原文/单词时用英语
- 单词释义允许直接给出（释义是工具，不是答案）
- 语法规则允许直接陈述（规则是工具），但不替学生应用规则
  ✅ "第三人称单数后面动词要加 s，这是规则。那 he 后面的 go 应该怎么变？"
  ❌ "选 goes，因为第三人称单数要加 s。"`
}
